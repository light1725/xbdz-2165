/*****************************************************************************************************
 * @file    Key.h
 * @brief   兴邦电器 0010902165 按键板按键检测驱动头文件
 * @details 严格对应用户定义:
 *          按键2 (K2) = TK15 (P2.7) -> 控制 LED2 (P0.7)
 *          按键3 (K3) = TK16 (P1.7) -> 控制 LED3 (P0.6)
 *          按键4 (K4) = TK12 (P2.4) -> 控制 LED4 (P0.3)
 *          按键5 (K5) = TK13 (P2.5) -> 控制 LED5 (P0.1)
 *****************************************************************************************************/
#ifndef _KEY_H_
#define _KEY_H_

#include "BSP.h"

/*******************************************************************************
 * 触控按键通道掩码 (基于 SC92F8463B 物理引脚与 TK 通道配置)
 *******************************************************************************/
#define TK_MASK_K2          (1UL << 15)  // 按键2: P2.7 (TK15)
#define TK_MASK_K3          (1UL << 16)  // 按键3: P1.7 (TK16)
#define TK_MASK_K4          (1UL << 12)  // 按键4: P2.4 (TK12)
#define TK_MASK_K5          (1UL << 13)  // 按键5: P2.5 (TK13)

/*******************************************************************************
 * 按键事件枚举定义
 *******************************************************************************/
typedef enum {
    KEY_EVENT_NONE = 0,
    KEY_EVENT_K2_CLICK,         // 按键2 (TK15 / P2.7) 短按 -> 翻转 LED2
    KEY_EVENT_K3_CLICK,         // 按键3 (TK16 / P1.7) 短按 -> 翻转 LED3
    KEY_EVENT_K4_CLICK,         // 按键4 (TK12 / P2.4) 短按 -> 翻转 LED4
    KEY_EVENT_K5_CLICK          // 按键5 (TK13 / P2.5) 短按 -> 翻转 LED5
} KeyEvent_t;

/*******************************************************************************
 * 函数声明
 *******************************************************************************/
void Key_Init(void);
KeyEvent_t Key_Scan_10ms(unsigned long int tk_flag);

#endif /* _KEY_H_ */
